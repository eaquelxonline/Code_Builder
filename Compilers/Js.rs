impl Lexer {
    fn new(source: &str) -> Lexer {
        Lexer {
            chars: source.chars().collect(),
            pos: 0,
            line: 1,
            line_start: 0,
            html_comments: true,
        }
    }

    fn peek(&self, ahead: usize) -> Option<char> {
        self.chars.get(self.pos + ahead).copied()
    }

    fn problem(&self, message: &str, at: usize) -> Problem {
        let mut line = 1u32;
        let mut start = 0usize;
        let mut index = 0usize;
        while index < at.min(self.chars.len()) {
            let character = self.chars[index];
            if character == '\r' && self.chars.get(index + 1) == Some(&'\n') {
                index += 1;
            }
            if is_line_break(character) || (character == '\r') {
                line += 1;
                start = index + 1;
            }
            index += 1;
        }
        Problem {
            message: message.to_string(),
            line,
            column: (at - start.min(at)) as u32,
        }
    }

    fn newline(&mut self) {
        self.line += 1;
        self.line_start = self.pos;
    }

    fn skip_space(&mut self) -> Result<bool, Problem> {
        let mut newline = false;
        loop {
            match self.peek(0) {
                Some(character) if is_space(character) => self.pos += 1,
                Some('\r') => {
                    self.pos += 1;
                    if self.peek(0) == Some('\n') {
                        self.pos += 1;
                    }
                    self.newline();
                    newline = true;
                }
                Some(character) if is_line_break(character) => {
                    self.pos += 1;
                    self.newline();
                    newline = true;
                }
                Some('/') if self.peek(1) == Some('/') => {
                    while let Some(character) = self.peek(0) {
                        if is_line_break(character) {
                            break;
                        }
                        self.pos += 1;
                    }
                }
                Some('/') if self.peek(1) == Some('*') => {
                    let begin = self.pos;
                    self.pos += 2;
                    loop {
                        match self.peek(0) {
                            None => return Err(self.problem("Unterminated comment", begin)),
                            Some('*') if self.peek(1) == Some('/') => {
                                self.pos += 2;
                                break;
                            }
                            Some('\r') => {
                                self.pos += 1;
                                if self.peek(0) == Some('\n') {
                                    self.pos += 1;
                                }
                                self.newline();
                                newline = true;
                            }
                            Some(character) if is_line_break(character) => {
                                self.pos += 1;
                                self.newline();
                                newline = true;
                            }
                            Some(_) => self.pos += 1,
                        }
                    }
                }
                Some('<')
                    if self.html_comments
                        && self.peek(1) == Some('!')
                        && self.peek(2) == Some('-')
                        && self.peek(3) == Some('-') =>
                {
                    while let Some(character) = self.peek(0) {
                        if is_line_break(character) {
                            break;
                        }
                        self.pos += 1;
                    }
                }
                Some('-')
                    if self.html_comments
                        && (newline || self.pos == 0)
                        && self.peek(1) == Some('-')
                        && self.peek(2) == Some('>') =>
                {
                    while let Some(character) = self.peek(0) {
                        if is_line_break(character) {
                            break;
                        }
                        self.pos += 1;
                    }
                }
                _ => return Ok(newline),
            }
        }
    }

    fn hex_digits(&mut self, count: usize) -> Result<u32, Problem> {
        let begin = self.pos;
        let mut value = 0u32;
        for _ in 0..count {
            match self.peek(0).and_then(|character| character.to_digit(16)) {
                Some(digit) => {
                    value = value * 16 + digit;
                    self.pos += 1;
                }
                None => return Err(self.problem("Bad character escape sequence", begin)),
            }
        }
        Ok(value)
    }

    fn unicode_escape(&mut self) -> Result<u32, Problem> {
        if self.peek(0) == Some('{') {
            let begin = self.pos;
            self.pos += 1;
            let mut value = 0u32;
            let mut count = 0;
            while let Some(digit) = self.peek(0).and_then(|character| character.to_digit(16)) {
                value = value.saturating_mul(16).saturating_add(digit);
                self.pos += 1;
                count += 1;
            }
            if count == 0 || self.peek(0) != Some('}') || value > 0x10ffff {
                return Err(self.problem("Bad character escape sequence", begin));
            }
            self.pos += 1;
            Ok(value)
        } else {
            self.hex_digits(4)
        }
    }

    fn read_name(&mut self) -> Result<(String, bool), Problem> {
        let mut name = String::new();
        let mut escaped = false;
        loop {
            match self.peek(0) {
                Some('\\') => {
                    let begin = self.pos;
                    self.pos += 1;
                    if self.peek(0) != Some('u') {
                        return Err(
                            self.problem("Expecting Unicode escape sequence \\uXXXX", begin)
                        );
                    }
                    self.pos += 1;
                    let code = self.unicode_escape()?;
                    let character = char::from_u32(code)
                        .ok_or_else(|| self.problem("Invalid Unicode escape", begin))?;
                    let allowed = if name.is_empty() {
                        is_id_start(character)
                    } else {
                        is_id_part(character)
                    };
                    if !allowed {
                        return Err(self.problem("Invalid Unicode escape", begin));
                    }
                    name.push(character);
                    escaped = true;
                }
                Some(character)
                    if (name.is_empty() && is_id_start(character))
                        || (!name.is_empty() && is_id_part(character)) =>
                {
                    name.push(character);
                    self.pos += 1;
                }
                _ => break,
            }
        }
        Ok((name, escaped))
    }

    fn read_digits(&mut self, radix: u32, allow_separator: bool) -> Result<String, Problem> {
        let mut digits = String::new();
        let begin = self.pos;
        loop {
            match self.peek(0) {
                Some('_') if allow_separator => {
                    if digits.is_empty()
                        || self.peek(1).and_then(|next| next.to_digit(radix)).is_none()
                    {
                        return Err(self.problem("Numeric separator is not allowed here", self.pos));
                    }
                    self.pos += 1;
                }
                Some(character) if character.is_digit(radix) => {
                    digits.push(character);
                    self.pos += 1;
                }
                _ => break,
            }
        }
        if digits.is_empty() && self.pos == begin {
            return Ok(digits);
        }
        Ok(digits)
    }

    fn read_number(&mut self) -> Result<Tok, Problem> {
        let begin = self.pos;
        let first = self.peek(0);
        if first == Some('0') {
            let radix = match self.peek(1) {
                Some('x') | Some('X') => 16,
                Some('o') | Some('O') => 8,
                Some('b') | Some('B') => 2,
                _ => 0,
            };
            if radix != 0 {
                self.pos += 2;
                let digits = self.read_digits(radix, true)?;
                if digits.is_empty() {
                    return Err(self.problem("Expected number in radix", begin));
                }
                if self.peek(0) == Some('n') {
                    self.pos += 1;
                    self.check_after_number(begin)?;
                    let prefix = match radix {
                        16 => "0x",
                        8 => "0o",
                        _ => "0b",
                    };
                    return Ok(Tok::BigInt(format!("{prefix}{digits}")));
                }
                self.check_after_number(begin)?;
                let mut value = 0f64;
                for digit in digits.chars() {
                    value =
                        value * f64::from(radix) + f64::from(digit.to_digit(radix).unwrap_or(0));
                }
                return Ok(Tok::Number(value));
            }
            if matches!(self.peek(1), Some('0'..='9')) {
                let mut octal = true;
                let mut at = self.pos + 1;
                while let Some(character) = self.chars.get(at) {
                    if !character.is_ascii_digit() {
                        break;
                    }
                    if *character >= '8' {
                        octal = false;
                    }
                    at += 1;
                }
                if octal {
                    let digits: String = self.chars[self.pos + 1..at].iter().collect();
                    self.pos = at;
                    self.check_after_number(begin)?;
                    let mut value = 0f64;
                    for digit in digits.chars() {
                        value = value * 8.0 + f64::from(digit.to_digit(8).unwrap_or(0));
                    }
                    return Ok(Tok::Number(value));
                }
            }
        }
        let mut literal = String::new();
        if first == Some('0') && matches!(self.peek(1), Some('0'..='9') | Some('_')) {
            let mut at = self.pos + 1;
            let mut separated = false;
            while let Some(character) = self.chars.get(at) {
                if *character == '_' {
                    separated = true;
                } else if !character.is_ascii_digit() {
                    break;
                }
                at += 1;
            }
            if separated {
                return Err(
                    self.problem("Numeric separator can not be used after leading 0", begin)
                );
            }
            if self.chars.get(at) == Some(&'n') {
                return Err(self.problem("Invalid BigInt syntax", begin));
            }
        }
        if first != Some('.') {
            literal.push_str(&self.read_digits(10, true)?);
        }
        if self.peek(0) == Some('n') && first != Some('.') {
            self.pos += 1;
            self.check_after_number(begin)?;
            return Ok(Tok::BigInt(literal));
        }
        if self.peek(0) == Some('.') {
            self.pos += 1;
            literal.push('.');
            literal.push_str(&self.read_digits(10, true)?);
        }
        if matches!(self.peek(0), Some('e') | Some('E')) {
            let mut look = 1;
            if matches!(self.peek(look), Some('+') | Some('-')) {
                look += 1;
            }
            if self
                .peek(look)
                .is_some_and(|character| character.is_ascii_digit())
            {
                literal.push('e');
                self.pos += 1;
                if let Some(sign) = self.peek(0).filter(|sign| *sign == '+' || *sign == '-') {
                    literal.push(sign);
                    self.pos += 1;
                }
                literal.push_str(&self.read_digits(10, true)?);
            } else {
                return Err(self.problem("Invalid number", begin));
            }
        }
        self.check_after_number(begin)?;
        let normalized = if literal.starts_with('.') {
            format!("0{literal}")
        } else if literal.ends_with('.') {
            format!("{literal}0")
        } else {
            literal.replace(".e", ".0e")
        };
        normalized
            .parse::<f64>()
            .map(Tok::Number)
            .map_err(|_| self.problem("Invalid number", begin))
    }

    fn check_after_number(&self, begin: usize) -> Result<(), Problem> {
        match self.peek(0) {
            Some(character)
                if is_id_start(character) || character.is_ascii_digit() || character == '\\' =>
            {
                Err(self.problem("Identifier directly after number", begin))
            }
            _ => Ok(()),
        }
    }

    fn push_code(&self, out: &mut String, code: u32) {
        out.push(char::from_u32(code).unwrap_or('\u{fffd}'));
    }

    fn read_escape(&mut self, out: &mut String, in_template: bool) -> Result<bool, Problem> {
        let begin = self.pos;
        self.pos += 1;
        let Some(character) = self.peek(0) else {
            return Err(self.problem("Unterminated string constant", begin));
        };
        self.pos += 1;
        match character {
            'n' => out.push('\n'),
            'r' => out.push('\r'),
            't' => out.push('\t'),
            'b' => out.push('\u{8}'),
            'v' => out.push('\u{b}'),
            'f' => out.push('\u{c}'),
            'x' => {
                let code = self.hex_digits(2)?;
                self.push_code(out, code);
            }
            'u' => {
                let code = self.unicode_escape()?;
                if (0xd800..0xdc00).contains(&code)
                    && self.peek(0) == Some('\\')
                    && self.peek(1) == Some('u')
                {
                    let save = self.pos;
                    self.pos += 2;
                    match self.unicode_escape() {
                        Ok(low) if (0xdc00..0xe000).contains(&low) => {
                            self.push_code(out, 0x10000 + ((code - 0xd800) << 10) + (low - 0xdc00));
                            return Ok(true);
                        }
                        _ => self.pos = save,
                    }
                }
                self.push_code(out, code);
            }
            '\r' => {
                if self.peek(0) == Some('\n') {
                    self.pos += 1;
                }
                self.newline();
            }
            character if is_line_break(character) => self.newline(),
            '0'..='7' => {
                if character == '0' && !matches!(self.peek(0), Some('0'..='9')) {
                    out.push('\0');
                } else if in_template {
                    return Err(self.problem(
                        "Octal escape sequences are not allowed in template strings",
                        begin,
                    ));
                } else {
                    let mut value = character.to_digit(8).unwrap_or(0);
                    let limit = if character <= '3' { 2 } else { 1 };
                    for _ in 0..limit {
                        match self.peek(0).and_then(|next| next.to_digit(8)) {
                            Some(digit) => {
                                value = value * 8 + digit;
                                self.pos += 1;
                            }
                            None => break,
                        }
                    }
                    self.push_code(out, value);
                }
            }
            '8' | '9' if in_template => {
                return Err(self.problem(
                    "Escape sequences \\8 and \\9 are not allowed in template strings",
                    begin,
                ));
            }
            other => out.push(other),
        }
        Ok(true)
    }

    fn read_string(&mut self, quote: char) -> Result<Tok, Problem> {
        let begin = self.pos;
        self.pos += 1;
        let mut out = String::new();
        loop {
            match self.peek(0) {
                None => return Err(self.problem("Unterminated string constant", begin)),
                Some(character) if character == quote => {
                    self.pos += 1;
                    return Ok(Tok::Str(out));
                }
                Some('\\') => {
                    self.read_escape(&mut out, false)?;
                }
                Some('\n') | Some('\r') => {
                    return Err(self.problem("Unterminated string constant", begin))
                }
                Some(character) => {
                    out.push(character);
                    self.pos += 1;
                }
            }
        }
    }

    fn read_template_chunk(&mut self) -> Result<(Option<String>, String, bool), Problem> {
        let begin = self.pos;
        let mut cooked = Some(String::new());
        let mut raw = String::new();
        loop {
            match self.peek(0) {
                None => return Err(self.problem("Unterminated template", begin)),
                Some('`') => {
                    self.pos += 1;
                    return Ok((cooked, raw, true));
                }
                Some('$') if self.peek(1) == Some('{') => {
                    self.pos += 2;
                    return Ok((cooked, raw, false));
                }
                Some('\\') => {
                    let from = self.pos;
                    let mut scratch = String::new();
                    let result = self.read_escape(&mut scratch, true);
                    let consumed: String = self.chars[from..self.pos].iter().collect();
                    raw.push_str(&consumed.replace("\r\n", "\n").replace('\r', "\n"));
                    match result {
                        Ok(_) => {
                            if let Some(value) = cooked.as_mut() {
                                value.push_str(&scratch);
                            }
                        }
                        Err(_) => {
                            cooked = None;
                            if self.pos == from {
                                self.pos += 1;
                            }
                        }
                    }
                }
                Some('\r') => {
                    self.pos += 1;
                    if self.peek(0) == Some('\n') {
                        self.pos += 1;
                    }
                    self.newline();
                    raw.push('\n');
                    if let Some(value) = cooked.as_mut() {
                        value.push('\n');
                    }
                }
                Some(character) => {
                    self.pos += 1;
                    if is_line_break(character) {
                        self.newline();
                    }
                    raw.push(character);
                    if let Some(value) = cooked.as_mut() {
                        value.push(character);
                    }
                }
            }
        }
    }

    fn read_regex(&mut self, begin: usize) -> Result<(String, String), Problem> {
        self.pos = begin + 1;
        let mut pattern = String::new();
        let mut in_class = false;
        loop {
            match self.peek(0) {
                None => return Err(self.problem("Unterminated regular expression", begin)),
                Some(character) if is_line_break(character) => {
                    return Err(self.problem("Unterminated regular expression", begin))
                }
                Some('\\') => {
                    pattern.push('\\');
                    self.pos += 1;
                    match self.peek(0) {
                        Some(next) if !is_line_break(next) => {
                            pattern.push(next);
                            self.pos += 1;
                        }
                        _ => return Err(self.problem("Unterminated regular expression", begin)),
                    }
                }
                Some('[') => {
                    in_class = true;
                    pattern.push('[');
                    self.pos += 1;
                }
                Some(']') => {
                    in_class = false;
                    pattern.push(']');
                    self.pos += 1;
                }
                Some('/') if !in_class => {
                    self.pos += 1;
                    break;
                }
                Some(character) => {
                    pattern.push(character);
                    self.pos += 1;
                }
            }
        }
        let mut flags = String::new();
        while let Some(character) = self.peek(0) {
            if is_id_part(character) {
                flags.push(character);
                self.pos += 1;
            } else {
                break;
            }
        }
        for (index, flag) in flags.char_indices() {
            if !"dgimsuvy".contains(flag) || flags[..index].contains(flag) {
                return Err(self.problem("Invalid regular expression flag", begin));
            }
        }
        Ok((pattern, flags))
    }

    fn next(&mut self) -> Result<Token, Problem> {
        let newline_before = self.skip_space()?;
        let start = self.pos;
        let line = self.line;
        let column = (start - self.line_start) as u32;
        let Some(character) = self.peek(0) else {
            return Ok(Token {
                tok: Tok::Eof,
                start,
                end: start,
                line,
                column,
                newline_before,
                escaped: false,
            });
        };
        let mut escaped = false;
        let tok = if is_id_start(character) || character == '\\' {
            let (name, was_escaped) = self.read_name()?;
            escaped = was_escaped;
            Tok::Name(name)
        } else if character == '#' && self.pos == 0 && self.peek(1) == Some('!') {
            while let Some(next) = self.peek(0) {
                if is_line_break(next) {
                    break;
                }
                self.pos += 1;
            }
            return self.next();
        } else if character == '#' {
            self.pos += 1;
            let (name, _) = self.read_name()?;
            if name.is_empty() {
                return Err(self.problem("Unexpected character '#'", start));
            }
            Tok::Private(name)
        } else if character.is_ascii_digit()
            || (character == '.' && self.peek(1).is_some_and(|next| next.is_ascii_digit()))
        {
            self.read_number()?
        } else if character == '"' || character == '\'' {
            self.read_string(character)?
        } else {
            let mut found = None;
            for candidate in PUNCTUATORS {
                let length = candidate.chars().count();
                if (0..length).all(|offset| self.peek(offset) == candidate.chars().nth(offset)) {
                    if *candidate == "?." && self.peek(2).is_some_and(|next| next.is_ascii_digit())
                    {
                        continue;
                    }
                    found = Some((*candidate, length));
                    break;
                }
            }
            match found {
                Some((punct, length)) => {
                    self.pos += length;
                    Tok::Punct(punct)
                }
                None => {
                    return Err(self.problem(&format!("Unexpected character '{character}'"), start))
                }
            }
        };
        Ok(Token {
            tok,
            start,
            end: self.pos,
            line,
            column,
            newline_before,
            escaped,
        })
    }
}

