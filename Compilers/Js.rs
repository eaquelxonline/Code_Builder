#[derive(Clone, Debug, PartialEq)]
pub enum Value {
    Null,
    Bool(bool),
    Number(f64),
    Text(String),
    Node(Box<Node>),
    List(Vec<Value>),
    Regex { pattern: String, flags: String },
    BigInt(String),
}

#[derive(Clone, Debug, PartialEq)]
pub struct Node {
    pub kind: &'static str,
    pub fields: Vec<(&'static str, Value)>,
    pub line: u32,
    pub column: u32,
}

impl Node {
    pub fn new(kind: &'static str, line: u32, column: u32) -> Node {
        Node {
            kind,
            fields: Vec::new(),
            line,
            column,
        }
    }

    pub fn with(mut self, key: &'static str, value: Value) -> Node {
        self.set(key, value);
        self
    }

    pub fn set(&mut self, key: &'static str, value: Value) {
        for field in self.fields.iter_mut() {
            if field.0 == key {
                field.1 = value;
                return;
            }
        }
        self.fields.push((key, value));
    }

    pub fn get(&self, key: &str) -> Option<&Value> {
        self.fields
            .iter()
            .find(|field| field.0 == key)
            .map(|field| &field.1)
    }

    pub fn text(&self, key: &str) -> Option<&str> {
        match self.get(key) {
            Some(Value::Text(text)) => Some(text.as_str()),
            _ => None,
        }
    }

    pub fn flag(&self, key: &str) -> bool {
        matches!(self.get(key), Some(Value::Bool(true)))
    }

    pub fn node(&self, key: &str) -> Option<&Node> {
        match self.get(key) {
            Some(Value::Node(node)) => Some(node),
            _ => None,
        }
    }

    pub fn list(&self, key: &str) -> &[Value] {
        match self.get(key) {
            Some(Value::List(items)) => items,
            _ => &[],
        }
    }
}

fn node_value(node: Node) -> Value {
    Value::Node(Box::new(node))
}

fn nodes(items: Vec<Node>) -> Value {
    Value::List(items.into_iter().map(node_value).collect())
}

fn text(value: &str) -> Value {
    Value::Text(value.to_string())
}

#[derive(Clone, Debug, PartialEq)]
pub struct Program {
    pub body: Vec<Node>,
    pub module: bool,
}

impl Program {
    pub fn to_node(&self) -> Node {
        Node::new("Program", 1, 0)
            .with("body", nodes(self.body.clone()))
            .with(
                "sourceType",
                text(if self.module { "module" } else { "script" }),
            )
    }

    pub fn to_json(&self) -> String {
        let mut out = String::new();
        write_node(&self.to_node(), &mut out);
        out
    }
}

fn write_string(value: &str, out: &mut String) {
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other if (other as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", other as u32)),
            other => out.push(other),
        }
    }
    out.push('"');
}

fn write_number(value: f64, out: &mut String) {
    if value.is_nan() || value.is_infinite() {
        out.push_str("null");
    } else if value == value.trunc() && value.abs() < 1e15 {
        out.push_str(&format!("{}", value as i64));
    } else {
        out.push_str(&format!("{value}"));
    }
}

fn write_value(value: &Value, out: &mut String) {
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(flag) => out.push_str(if *flag { "true" } else { "false" }),
        Value::Number(number) => write_number(*number, out),
        Value::Text(text) => write_string(text, out),
        Value::Node(node) => write_node(node, out),
        Value::List(items) => {
            out.push('[');
            for (index, item) in items.iter().enumerate() {
                if index > 0 {
                    out.push(',');
                }
                write_value(item, out);
            }
            out.push(']');
        }
        Value::Regex { pattern, flags } => {
            out.push_str("{\"pattern\":");
            write_string(pattern, out);
            out.push_str(",\"flags\":");
            write_string(flags, out);
            out.push('}');
        }
        Value::BigInt(digits) => write_string(digits, out),
    }
}

fn write_node(node: &Node, out: &mut String) {
    out.push('{');
    if !node.kind.is_empty() {
        out.push_str("\"type\":");
        write_string(node.kind, out);
    }
    let mut first = node.kind.is_empty();
    for (key, value) in node.fields.iter() {
        if key.starts_with('_') {
            continue;
        }
        if !first {
            out.push(',');
        }
        first = false;
        write_string(key, out);
        out.push(':');
        write_value(value, out);
    }
    out.push('}');
}

