fn is_line_break(character: char) -> bool {
    matches!(character, '\n' | '\r' | '\u{2028}' | '\u{2029}')
}

fn is_space(character: char) -> bool {
    matches!(
        character,
        ' ' | '\t' | '\u{0b}' | '\u{0c}' | '\u{a0}' | '\u{feff}'
    ) || (character as u32 > 127 && character.is_whitespace() && !is_line_break(character))
}

fn in_ranges(table: &[u32], code: u32) -> bool {
    let mut low = 0;
    let mut high = table.len() / 2;
    while low < high {
        let middle = (low + high) / 2;
        if code < table[middle * 2] {
            high = middle;
        } else if code > table[middle * 2 + 1] {
            low = middle + 1;
        } else {
            return true;
        }
    }
    false
}

fn is_id_start(character: char) -> bool {
    if character.is_ascii() {
        return character.is_ascii_alphabetic() || character == '$' || character == '_';
    }
    in_ranges(ID_START_RANGES, character as u32)
}

fn is_id_part(character: char) -> bool {
    if character.is_ascii() {
        return character.is_ascii_alphanumeric() || character == '$' || character == '_';
    }
    character == '\u{200c}'
        || character == '\u{200d}'
        || in_ranges(ID_CONTINUE_RANGES, character as u32)
}

